import { useState, useEffect } from "react";
import { Link } from "react-router-dom";
import { BarChart, Bar, XAxis, YAxis, CartesianGrid, ResponsiveContainer, Cell } from "recharts";
import { TrendingUp, TrendingDown, Minus, ChevronDown, ChevronUp } from "lucide-react";
import { stocksAPI, predictionAPI } from "../services/api";
import { Segmented, Empty } from "./ui";
import NewsCard from "./NewsCard";

// Big money: crores for INR, B/T for USD.
function bigMoney(v, currency) {
  if (v == null || !isFinite(v)) return "—";
  if (currency === "INR") return `₹${Math.round(v / 1e7).toLocaleString("en-IN")}Cr`;
  if (Math.abs(v) >= 1e12) return `$${(v / 1e12).toFixed(2)}T`;
  return `$${(v / 1e9).toFixed(2)}B`;
}
const num = (v, d = 2) => (v == null || !isFinite(v) ? "—" : Number(v).toLocaleString("en-IN", { maximumFractionDigits: d }));
const pct = (v) => (v == null || !isFinite(v) ? "—" : `${num(v)}%`);
const growth = (now, then) => (now != null && then ? ((now - then) / Math.abs(then)) * 100 : null);

function Section({ title, children, action }) {
  return (
    <section className="ov-section">
      <div className="ov-head"><h2>{title}</h2>{action}</div>
      {children}
    </section>
  );
}

function Marker({ low, high, price, label }) {
  const ok = low > 0 && high > low && price > 0;
  const pos = ok ? Math.min(100, Math.max(0, ((price - low) / (high - low)) * 100)) : 0;
  return (
    <div className="ov-range">
      <div className="ov-range-ends">
        <div><span>{label} low</span><b>{low > 0 ? num(low) : "—"}</b></div>
        <div style={{ textAlign: "right" }}><span>{label} high</span><b>{high > 0 ? num(high) : "—"}</b></div>
      </div>
      <div className="ov-track">
        {ok && (
          <div className="ov-pin" style={{ left: `${pos}%`, "--shift": pos < 8 ? "0%" : pos > 92 ? "-100%" : "-50%" }}
            aria-label={`Current price ${num(price)}, ${Math.round(pos)}% of the way up the range`}>
            <i /><span>{num(price)}</span>
          </div>
        )}
      </div>
    </div>
  );
}

function Insights({ symbol, market }) {
  const [state, setState] = useState({ loading: true });
  const [open, setOpen] = useState(true);
  useEffect(() => {
    let live = true;
    setState({ loading: true });
    predictionAPI.insights(symbol, market)
      .then((r) => live && setState({ loading: false, ...r.data }))
      .catch(() => live && setState({ loading: false, available: false }));
    return () => { live = false; };
  }, [symbol, market]);

  if (state.loading) return null;
  if (!state.available) {
    if (state.reason !== "no_key") return null;
    return (
      <div className="ov-card">
        <b>AI insights</b>
        <p className="hint" style={{ margin: "6px 0 0" }}>Add a Groq or Google AI key on the <Link className="link" to="/api-keys">API Keys page</Link> to see short AI takeaways here.</p>
      </div>
    );
  }
  const Icon = { up: TrendingUp, down: TrendingDown }[state.insights[0]?.tone] || Minus;
  return (
    <div className="ov-card">
      <button className="ov-card-head" onClick={() => setOpen(!open)} aria-expanded={open}>
        <span><Icon size={18} color="var(--saffron)" /> AI insights</span>
        {open ? <ChevronUp size={18} /> : <ChevronDown size={18} />}
      </button>
      {open && state.insights.map((i) => {
        const T = { up: TrendingUp, down: TrendingDown }[i.tone] || Minus;
        return (
          <div className="ov-insight" key={i.label}>
            <div className={`ov-insight-label ${i.tone}`}><T size={16} /> {i.label}</div>
            <p>{i.text}</p>
          </div>
        );
      })}
      {open && <p className="hint" style={{ margin: "8px 0 0" }}>Generated by AI from reported results and recent headlines. Not advice.</p>}
    </div>
  );
}

function Performance({ q, currency }) {
  const price = q?.price;
  return (
    <Section title="Performance">
      <Marker label="Today's" low={q?.day_low} high={q?.day_high} price={price} />
      <Marker label="52 week" low={q?.week_52_low} high={q?.week_52_high} price={price} />
      <div className="ov-stats">
        {[["Open price", q?.day_open > 0 ? num(q.day_open) : "—"],
          ["Previous close", q?.prev_close > 0 ? num(q.prev_close) : "—"],
          ["Volume", q?.volume ? Number(q.volume).toLocaleString("en-IN") : "—"],
          ["Lower circuit", q?.lower_circuit > 0 ? num(q.lower_circuit) : "—"],
          ["Upper circuit", q?.upper_circuit > 0 ? num(q.upper_circuit) : "—"]]
          .filter(([k, v]) => !(currency !== "INR" && /circuit/.test(k)) && !(v === "—" && /Open|circuit/.test(k)))
          .map(([k, v]) => <div key={k}><span>{k}</span><b>{v}</b></div>)}
      </div>
    </Section>
  );
}

function Fundamentals({ f, currency }) {
  const rows = [
    ["Market Cap", f.market_cap != null ? bigMoney(f.market_cap, currency) : null, "ROE", f.roe != null ? pct(f.roe) : null],
    ["P/E Ratio(TTM)", f.pe != null ? num(f.pe) : null, "EPS(TTM)", f.eps != null ? num(f.eps) : null],
    ["P/B Ratio", f.pb != null ? num(f.pb) : null, "Dividend Yield", f.dividend_yield != null ? pct(f.dividend_yield) : null],
    ["Industry P/E", f.industry_pe != null ? num(f.industry_pe) : null, "Book Value", f.book_value != null ? num(f.book_value) : null],
    ["Debt to Equity", f.debt_to_equity != null ? num(f.debt_to_equity) : null, "Face Value", f.face_value != null ? num(f.face_value, 0) : null],
  ];
  if (rows.every((r) => !r[1] && !r[3])) return null;
  return (
    <Section title="Fundamentals">
      <div className="ov-kv">
        {rows.map((r, i) => (
          <div className="ov-kv-row" key={i}>
            <div><span>{r[0]}</span><b>{r[1] ?? "—"}</b></div>
            <div><span>{r[2]}</span><b>{r[3] ?? "—"}</b></div>
          </div>
        ))}
      </div>
    </Section>
  );
}

function Financials({ fin, currency }) {
  const [mode, setMode] = useState("quarterly");
  const [sel, setSel] = useState(null);
  const rows = fin?.[mode] || [];
  useEffect(() => setSel(null), [mode, fin]);
  if (!fin || (!fin.quarterly.length && !fin.yearly.length)) return null;
  const active = rows.length ? (sel ?? rows.length - 1) : 0;
  const cur = rows[active];
  const back = mode === "quarterly" ? 4 : 1;
  const prev = rows[active - back];
  const lastQ = fin.quarterly.at(-1), prevQ = fin.quarterly.at(-5);
  const lastY = fin.yearly.at(-1), prevY = fin.yearly.at(-2);
  const unit = currency === "INR" ? 1e7 : 1e9;
  const data = rows.map((r) => ({ ...r, rev: r.revenue / unit, prof: r.profit == null ? null : r.profit / unit }));
  const gl = (g) => g == null ? <span className="muted">—</span> : <b className={g >= 0 ? "pos" : "neg"}>{g >= 0 ? "+" : ""}{Math.round(g)}%</b>;
  return (
    <Section title="Financial performance"
      action={null}>
      <div style={{ marginBottom: 12 }}>
        <Segmented value={mode} onChange={setMode} label="Reporting period"
          options={[{ value: "quarterly", label: "Quarterly" }, { value: "yearly", label: "Yearly" }]} />
      </div>
      {rows.length === 0 ? <Empty title="No data">Not reported for this period.</Empty> : (
        <div className="ov-card">
          <div className="ov-fin-head">{cur?.period.toUpperCase()}</div>
          <div className="ov-fin-nums">
            <div><span>REVENUE</span><b>{bigMoney(cur?.revenue, currency)}</b> {prev && gl(growth(cur.revenue, prev.revenue))}</div>
            <div><span>PROFIT</span><b>{bigMoney(cur?.profit, currency)}</b> {prev && cur?.profit != null && gl(growth(cur.profit, prev.profit))}</div>
          </div>
          <ResponsiveContainer width="100%" height={220}>
            <BarChart data={data} barGap={4} onClick={(e) => e?.activeTooltipIndex != null && setSel(e.activeTooltipIndex)}>
              <CartesianGrid stroke="var(--rule-soft)" strokeDasharray="4 4" vertical={false} />
              <XAxis dataKey="period" tickLine={false} axisLine={{ stroke: "var(--rule)" }} tick={{ fontSize: 11, fill: "var(--mute)" }} />
              <YAxis orientation="right" tickLine={false} axisLine={false} width={54} tick={{ fontSize: 11, fill: "var(--mute)" }}
                tickFormatter={(v) => (v >= 1000 ? `${Math.round(v / 1000)}k` : v)} />
              <Bar dataKey="rev" radius={[4, 4, 0, 0]} maxBarSize={34}>
                {data.map((_, i) => <Cell key={i} fill="var(--mute)" fillOpacity={i === active ? 0.9 : 0.35} />)}
              </Bar>
              <Bar dataKey="prof" radius={[4, 4, 0, 0]} maxBarSize={34}>
                {data.map((_, i) => <Cell key={i} fill="var(--up)" fillOpacity={i === active ? 1 : 0.4} />)}
              </Bar>
            </BarChart>
          </ResponsiveContainer>
          <p className="hint" style={{ margin: 0 }}>Amounts in {currency === "INR" ? "₹ crore" : "$ billion"}. Tap a bar to see that period.</p>
        </div>
      )}
      <div className="ov-grow">
        <div>
          <span className="ov-cap">REVENUE GROWTH</span>
          <div><span>Latest quarter, year on year</span>{gl(growth(lastQ?.revenue, prevQ?.revenue))}</div>
          <div><span>Latest year</span>{gl(growth(lastY?.revenue, prevY?.revenue))}</div>
        </div>
        <div>
          <span className="ov-cap">PROFIT GROWTH</span>
          <div><span>Latest quarter, year on year</span>{gl(growth(lastQ?.profit, prevQ?.profit))}</div>
          <div><span>Latest year</span>{gl(growth(lastY?.profit, prevY?.profit))}</div>
        </div>
      </div>
    </Section>
  );
}

function About({ about, symbol, market }) {
  const [more, setMore] = useState(false);
  if (!about || !about.text) return null;
  const facts = [["CEO/MD", about.ceo], ["Founded in", about.founded], [`${market} symbol`, symbol.toUpperCase()], ["Industry", about.industry]].filter((f) => f[1]);
  return (
    <Section title="About">
      <p className={`ov-about ${more ? "" : "clamp"}`}>{about.text}</p>
      <button className="link" onClick={() => setMore(!more)}>{more ? "Show less" : "Read more"}</button>
      <div className="ov-stats" style={{ marginTop: 16 }}>{facts.map(([k, v]) => <div key={k}><span>{k}</span><b>{String(v)}</b></div>)}</div>
    </Section>
  );
}

const HOLD_COLORS = { Promoters: "#7C77C9", DII: "#9DB45A", FII: "#4A9FD9", Public: "#F59A23" };
function Shareholding({ holding }) {
  const periods = Object.keys(holding || {});
  const [p, setP] = useState(null);
  if (!periods.length) return null;
  const active = periods.includes(p) ? p : periods[periods.length - 1];
  return (
    <Section title="Shareholding pattern">
      <div className="ov-chips">
        {periods.map((k) => <button key={k} className="ov-chip" aria-pressed={k === active} onClick={() => setP(k)}>{k}</button>)}
      </div>
      <div className="ov-card" style={{ display: "grid", gap: 16 }}>
        {Object.entries(holding[active]).map(([k, v]) => (
          <div className="ov-hold" key={k}>
            <span>{k}</span>
            <div className="ov-bar"><i style={{ width: `${Math.min(100, v)}%`, background: HOLD_COLORS[k] || "var(--mute)" }} /></div>
            <b>{num(v)}%</b>
          </div>
        ))}
      </div>
    </Section>
  );
}

export default function OverviewTab({ symbol, market, currency, quote, news, onSeeNews }) {
  const [co, setCo] = useState({ loading: true });
  useEffect(() => {
    let live = true;
    setCo({ loading: true });
    stocksAPI.company(symbol, market).then((r) => live && setCo({ loading: false, ...r.data }))
      .catch(() => live && setCo({ loading: false, available: false }));
    return () => { live = false; };
  }, [symbol, market]);

  return (
    <div className="ov">
      <Insights symbol={symbol} market={market} />
      <Performance q={quote} currency={currency} />
      {co.loading ? null : (
        <>
          {co.fundamentals && <Fundamentals f={co.fundamentals} currency={currency} />}
          <Financials fin={co.financials} currency={currency} />
          <About about={co.about} symbol={symbol} market={market} />
          <Shareholding holding={co.shareholding} />
          {!co.available && (
            <p className="hint">Company details aren't available for this stock right now. The data source may be busy or blocking requests.</p>
          )}
        </>
      )}
      <Section title="Latest news" action={news.length > 3 ? <button className="link" onClick={onSeeNews}>See all</button> : null}>
        {news.length === 0 ? (
          <Empty title="No news found">No recent headlines turned up for this stock. The news sources may be unreachable.</Empty>
        ) : (
          <ul className="row-list">{news.slice(0, 3).map((a, i) => <li key={i}><NewsCard article={a} /></li>)}</ul>
        )}
      </Section>
    </div>
  );
}
