import { useMemo } from "react";
import { Link } from "react-router-dom";
import { theme } from "../theme";

// Decorative only: a seeded random walk drawn as candles. It does not represent real prices.
function Candles() {
  const candles = useMemo(() => {
    let seed = 7;
    const rnd = () => ((seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296);
    let price = 240;
    return Array.from({ length: 34 }, (_, i) => {
      const open = price;
      const close = open + (rnd() - 0.44) * 46;
      const high = Math.max(open, close) + rnd() * 22;
      const low = Math.min(open, close) - rnd() * 22;
      price = close;
      return { i, open, close, high, low };
    });
  }, []);

  return (
    <svg className="auth-candles" viewBox="0 0 680 420" preserveAspectRatio="none" aria-hidden="true">
      {candles.map((c) => {
        const x = 12 + c.i * 20;
        const y = (v) => 420 - v;
        const up = c.close >= c.open;
        const color = up ? theme.up : theme.down;
        return (
          <g key={c.i}>
            <line x1={x + 6} x2={x + 6} y1={y(c.high)} y2={y(c.low)} stroke={color} strokeWidth="1.5" />
            <rect x={x} y={y(Math.max(c.open, c.close))} width="12" height={Math.max(3, Math.abs(c.close - c.open))} fill={color} />
          </g>
        );
      })}
    </svg>
  );
}

export function Brand() {
  return (
    <Link to="/" className="auth-lockup">
      <span className="rail-brand" aria-hidden="true">S</span>
      StockSense AI
    </Link>
  );
}

export default function AuthShell({ title, subtitle, children, footer }) {
  return (
    <div className="auth">
      <aside className="auth-art">
        <Brand />
        <Candles />
        <div>
          <h1 className="auth-headline">Prices, news and an AI read on every stock you follow.</h1>
          <ul className="auth-points">
            <li>NSE, BSE and US markets in one place</li>
            <li>Predictions built from news sentiment and technical indicators</li>
            <li>Price alerts that tell you when a level is hit</li>
          </ul>
        </div>
        <p className="muted" style={{ fontSize: 12 }}>
          Predictions are generated by an AI model and are not financial advice.
        </p>
      </aside>

      <main className="auth-form-wrap">
        <div className="auth-card">
          <div className="auth-mobile-brand"><Brand /></div>
          <h2>{title}</h2>
          <p className="muted" style={{ margin: "6px 0 26px" }}>{subtitle}</p>
          {children}
          {footer && <p className="muted" style={{ marginTop: 22 }}>{footer}</p>}
        </div>
      </main>
    </div>
  );
}
